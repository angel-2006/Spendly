import os
import sqlite3

from flask import Flask, redirect, render_template, request, session, url_for
from werkzeug.security import check_password_hash

from database.db import (  # noqa: F401
    create_user,
    get_db,
    get_user_by_email,
    get_user_by_id,
    init_db,
    seed_db,
)

app = Flask(__name__)
# Development-only fallback; set SECRET_KEY in the environment for real use.
app.secret_key = os.environ.get("SECRET_KEY", "dev-only-insecure-key-change-me")


def _current_user():
    """Return the logged-in user row, or None (also None for a stale session)."""
    return get_user_by_id(session.get("user_id"))


@app.context_processor
def inject_current_user():
    return {"current_user": _current_user()}


with app.app_context():
    init_db()
    seed_db()


